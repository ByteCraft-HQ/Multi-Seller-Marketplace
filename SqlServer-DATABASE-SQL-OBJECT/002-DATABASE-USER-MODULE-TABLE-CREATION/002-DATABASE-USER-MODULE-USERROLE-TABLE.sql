


CREATE TABLE [ROLES].[USERROLE]
(
UserRoleId BIGINT NOT NULL IDENTITY(1,1),
UserId BIGINT NOT NULL ,
RoleId TINYINT NOT NULL,
UserRoleStatus VARCHAR(20) NOT NULL,
UserRoleActiveNow BIT NOT NULL DEFAULT 0,

CONSTRAINT UserRoleId_USERROLE_PK PRIMARY KEY(UserRoleId) ,

CONSTRAINT UserId_USERROLE_FK FOREIGN KEY (UserId) REFERENCES [USERS].[USER](UserId)
ON UPDATE NO ACTION ON DELETE NO ACTION ,

CONSTRAINT RoleId_USERROLE_FK FOREIGN KEY (RoleId) REFERENCES [ROLES].[ROLE](RoleId)
ON UPDATE NO ACTION ON DELETE NO ACTION ,

CONSTRAINT UserIdAndRoleId_USERROLE_UQ UNIQUE (UserId, RoleId) ,

CONSTRAINT UserRoleStatus_USERROLE_CHECK CHECK (
    UserRoleStatus COLLATE Latin1_General_100_BIN2
    IN (
        'PENDING',
        'UNDERREVIEW',
        'ACTIVE',
        'DEACTIVATED',
        'DELETED'
    )
)

);

