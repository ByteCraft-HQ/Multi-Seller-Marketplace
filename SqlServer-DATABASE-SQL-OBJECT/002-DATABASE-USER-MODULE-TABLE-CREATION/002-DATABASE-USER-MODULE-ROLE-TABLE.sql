

CREATE TABLE [ROLES].[ROLE]
(
RoleId TINYINT NOT NULL IDENTITY(1,1),
RoleCategoryName VARCHAR(50) NOT NULL ,
RoleName VARCHAR(50) NOT NULL ,
RoleStatus VARCHAR(20) NOT NULL DEFAULT 'PENDEING',
RoleCreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),

CONSTRAINT RoleId_ROLE_PK PRIMARY KEY (RoleId),

CONSTRAINT RoleCategoryName_ROLE_FK FOREIGN KEY(RoleCategoryName) REFERENCES [ROLE].ROLECATEGORY(RoleCategoryName)
ON UPDATE CASCADE ON DELETE NO ACTION ,

CONSTRAINT RoleName_ROLE_UQ UNIQUE (RoleName),

CONSTRAINT RoleName_ROLE_CHECK CHECK (
    LEN(RoleName) > 0
    AND RoleName COLLATE Latin1_General_100_BIN2
        NOT LIKE '%[^A-Z0-9]%'
),

CONSTRAINT RoleStatus_ROLE_CHECK CHECK (
    RoleStatus COLLATE Latin1_General_100_BIN2
    IN (
        'PENDING',
        'UNDERREVIEW',
        'ACTIVE',
        'DEACTIVATED',
        'DELETED'
    )
),

CONSTRAINT RoleCreatedAt_ROLE_CHECK CHECK(RoleCreatedAt <= SYSDATETIME() )

);